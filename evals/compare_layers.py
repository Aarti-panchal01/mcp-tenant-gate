"""Before / after on the frozen test split: rules only vs rules + classifier.

    python -m evals.compare_layers

The test split (evals/data/SPLIT.json) is scored here and nowhere is anything
chosen from it. Intervals: Wilson 95% for rates, percentile bootstrap (10,000
resamples, fixed seed) for the paired recall difference.

Benign sets:
- deepset test benign rows (56, chat style questions)
- Python stdlib docstring paragraphs from modules on the "eval" side of the
  file name hash (the classifier never saw them; the other side was used as
  extra training negatives). The rules-only layer is scored on the same rows.

Writes results/injection-layers.md and .json.
"""

from __future__ import annotations

import json
import math
import random
import time

from evals.injection_eval import ROOT, SOURCE, load, stdlib_paragraphs_by_file, stdlib_side
from mcp_tenant_gate.scanners import classifier
from mcp_tenant_gate.scanners.injection import decide


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def fmt(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.1f}% (95% CI {100 * lo:.1f} to {100 * hi:.1f})"


def run_config(texts: list[str], use_clf: bool, mode: str = "quarantine") -> tuple[list[str], float]:
    t0 = time.perf_counter()
    actions = [decide(t, mode, "eval", use_classifier=use_clf).action for t in texts]
    return actions, (time.perf_counter() - t0) * 1000 / max(1, len(texts))


def bootstrap_diff(a: list[bool], b: list[bool], n: int = 10000, seed: int = 11) -> tuple[float, float]:
    rng = random.Random(seed)
    m = len(a)
    diffs = []
    for _ in range(n):
        idx = [rng.randrange(m) for _ in range(m)]
        diffs.append(sum(b[i] - a[i] for i in idx) / m)
    diffs.sort()
    return diffs[int(0.025 * n)], diffs[int(0.975 * n)]


def main() -> None:
    rows = load()
    test = [r for r in rows if r["split"] == "test"]
    inj = [r["text"] for r in test if r["label"] == 1]
    ben = [r["text"] for r in test if r["label"] == 0]
    std = [p for f, p in stdlib_paragraphs_by_file() if stdlib_side(f) == "eval"]
    model = classifier.load_model()
    res: dict = {"source": SOURCE, "test_injections": len(inj), "test_benign": len(ben), "stdlib_eval_paragraphs": len(std),
                 "model": {k: v for k, v in model.items() if k != "weights"}, "configs": {}}
    per_inj: dict[str, list[bool]] = {}
    for name, use_clf in (("rules only", False), ("rules + classifier", True)):
        a_inj, ms_inj = run_config(inj, use_clf)
        a_ben, _ = run_config(ben, use_clf)
        a_std, ms_std = run_config(std, use_clf)
        per_inj[name] = [a == "quarantine" for a in a_inj]
        res["configs"][name] = {
            "withheld": sum(per_inj[name]), "flagged": sum(a != "pass" for a in a_inj),
            "benign_chat_withheld": sum(a == "quarantine" for a in a_ben), "benign_chat_flagged": sum(a != "pass" for a in a_ben),
            "stdlib_withheld": sum(a == "quarantine" for a in a_std), "stdlib_flagged": sum(a != "pass" for a in a_std),
            "ms_per_text_injection_rows": round(ms_inj, 3), "ms_per_text_stdlib_paragraphs": round(ms_std, 3)}
    lo, hi = bootstrap_diff(per_inj["rules only"], per_inj["rules + classifier"])
    res["recall_gain_withheld_ci"] = [round(lo, 4), round(hi, 4)]
    only_new = sum(b and not a for a, b in zip(per_inj["rules only"], per_inj["rules + classifier"]))
    lost = sum(a and not b for a, b in zip(per_inj["rules only"], per_inj["rules + classifier"]))
    res["newly_withheld"], res["no_longer_withheld"] = only_new, lost

    n_inj, n_ben, n_std = len(inj), len(ben), len(std)
    L = ["# Second layer: before and after on the frozen test split", "",
         f"Data: {SOURCE}. Test split, never used for training or thresholds (hashes in `evals/data/SPLIT.json`). "
         "Generated by `python -m evals.compare_layers`.", "",
         "Withheld = result quarantined. Flagged = withheld or wrapped in untrusted-data markers.", "",
         "| | Rules only (before) | Rules + classifier (after) |", "|---|---|---|"]
    c0, c1 = res["configs"]["rules only"], res["configs"]["rules + classifier"]
    L.append(f"| Injections withheld | {fmt(c0['withheld'], n_inj)} | {fmt(c1['withheld'], n_inj)} |")
    L.append(f"| Injections flagged | {fmt(c0['flagged'], n_inj)} | {fmt(c1['flagged'], n_inj)} |")
    L.append(f"| Benign chat rows withheld | {fmt(c0['benign_chat_withheld'], n_ben)} | {fmt(c1['benign_chat_withheld'], n_ben)} |")
    L.append(f"| Benign chat rows flagged | {fmt(c0['benign_chat_flagged'], n_ben)} | {fmt(c1['benign_chat_flagged'], n_ben)} |")
    L.append(f"| Benign stdlib docs withheld | {fmt(c0['stdlib_withheld'], n_std)} | {fmt(c1['stdlib_withheld'], n_std)} |")
    L.append(f"| Benign stdlib docs flagged | {fmt(c0['stdlib_flagged'], n_std)} | {fmt(c1['stdlib_flagged'], n_std)} |")
    L.append(f"| Time per text (injection rows) | {c0['ms_per_text_injection_rows']} ms | {c1['ms_per_text_injection_rows']} ms |")
    L.append(f"| Time per text (stdlib paragraphs, longer) | {c0['ms_per_text_stdlib_paragraphs']} ms | {c1['ms_per_text_stdlib_paragraphs']} ms |")
    L += ["", f"Paired difference in withheld recall: {100 * (c1['withheld'] - c0['withheld']) / n_inj:+.1f} points "
          f"(bootstrap 95% interval {100 * lo:+.1f} to {100 * hi:+.1f}). {only_new} injections newly withheld, {lost} no longer withheld.",
          "", f"Classifier: {res['model']['kind']}, C={res['model']['C']}, t_high={res['model']['t_high']}, "
          f"t_low={res['model']['t_low']}. {res['model']['trained_on']}.", ""]
    (ROOT / "results" / "injection-layers.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (ROOT / "results" / "injection-layers.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
